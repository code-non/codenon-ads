// Builds cards.html, the full preview sheet, from assets/sheet.html + every sets/NN-*.html.
// A set file is its own <style> block followed by its <section>; edit those, never cards.html.
// Usage: npm run build   (render-cards.sh runs it first, so renders never use a stale sheet)
const fs = require('fs');
const path = require('path');

const SETS = path.join(__dirname, 'sets');
const read = (f) => fs.readFileSync(f, 'utf8').replace(/\r\n/g, '\n');

function build() {
  const files = fs.readdirSync(SETS).filter((f) => /^\d{2}-.+\.html$/.test(f)).sort();
  let css = '', markup = '';
  for (const f of files) {
    const m = read(path.join(SETS, f)).match(/^<style>\n([\s\S]*?)<\/style>\n([\s\S]*)$/);
    if (!m) throw new Error(f + ': expected a <style> block followed by the set markup');
    css += m[1];
    markup += m[2].trimEnd() + '\n\n';
  }
  // Function replacements, so "$" in CSS or markup is never read as a pattern.
  return read(path.join(__dirname, 'assets/sheet.html'))
    .replace('<!doctype html>\n', () => '<!doctype html>\n<!-- GENERATED by build-sheet.js from assets/sheet.html + sets/*.html. Edit those, then: npm run build -->\n')
    .replace('/* @css */\n', () => css)
    .replace('<!-- @sets -->\n', () => markup);
}

if (require.main === module) {
  fs.writeFileSync(path.join(__dirname, 'cards.html'), build());
  console.log('cards.html built from ' + fs.readdirSync(SETS).filter((f) => f.endsWith('.html')).length + ' set files');
}

module.exports = { build };
