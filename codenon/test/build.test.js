// build-sheet.js stitches sets/*.html into the full preview sheet (cards.html).
const test = require('node:test');
const assert = require('node:assert');
const fs = require('node:fs');
const path = require('node:path');
const { build } = require('../build-sheet.js');

const SETS = path.join(__dirname, '../sets');
const files = fs.readdirSync(SETS).filter((f) => /^\d{2}-.+\.html$/.test(f)).sort();
const html = build();

test('every set file is stitched in once, in number order', () => {
  assert.ok(files.length >= 35, 'expected one file per design');
  const order = [...html.matchAll(/<!-- (\d{2}) -->\n<section class="set">/g)].map((m) => m[1]);
  assert.deepStrictEqual(order, files.map((f) => f.slice(0, 2)));
});

test("each set's CSS ends up in the sheet's style block", () => {
  const style = html.slice(html.indexOf('<style>'), html.indexOf('</style>'));
  for (const f of files) {
    const own = fs.readFileSync(path.join(SETS, f), 'utf8').match(/<style>\n([\s\S]*?)<\/style>/);
    assert.ok(own, f + ' has no <style> block');
    assert.ok(style.includes(own[1]), f + ' CSS missing from the sheet');
  }
});

test('the sheet is marked as generated and loads the shared styles and script', () => {
  assert.match(html, /GENERATED by build-sheet\.js/);
  assert.match(html, /<link rel="stylesheet" href="assets\/sheet\.css">/);
  assert.match(html, /<script src="assets\/sheet\.js"><\/script>/);
  assert.ok(!/<!-- @|\/\* @/.test(html), 'unfilled template slot');
});
